# ── main ─────────────────────────────────────────────────────────────────────

def main() -> None:
    print("=" * 60)
    print("Aegon Skill Creator — scaffold a new skill")
    print("=" * 60)

    raw_name = _ask("\nSkill name (snake_case, e.g. 'reminder' or 'smart_home')")
    try:
        name = _validate_name(raw_name)
    except ValueError as e:
        print(f"Error: {e}")
        sys.exit(1)

    if (TOOLS_DIR / name).exists():
        print(f"Error: tools/{name}/ already exists. Choose a different name.")
        sys.exit(1)

    description = _ask(
        "One-sentence description (the intent classifier reads this)",
        default=f"TODO: describe {name}",
    )
    domain    = _choose("Domain", DOMAINS)
    mechanism = _choose("Mechanism", MECHANISMS)
    perm      = _choose("Permission level", PERMISSION_LEVELS)
    style     = _choose("Response style", RESPONSE_STYLES)

    cfg = {
        "name":             name,
        "class_name":       _to_class_name(name),
        "description":      description,
        "domain":           domain,
        "mechanism":        mechanism,
        "permission_level": perm,
        "response_style":   style,
    }

    skill_dir = TOOLS_DIR / name
    skill_dir.mkdir(parents=True)

    (skill_dir / "connector.json").write_text(_connector_json(cfg), encoding="utf-8")
    (skill_dir / f"{name}_tool.py").write_text(_tool_py(cfg), encoding="utf-8")
    (skill_dir / "__init__.py").write_text(_init_py(cfg), encoding="utf-8")
    (TESTS_DIR / f"test_{name}.py").write_text(_test_stub(cfg), encoding="utf-8")

    print(f"\n{'=' * 60}")
    print(f"Skill '{name}' scaffolded:")
    print(f"  tools/{name}/connector.json    (enabled: false — DO NOT change yet)")
    print(f"  tools/{name}/{name}_tool.py    (fill in validate() and execute())")
    print(f"  tools/{name}/__init__.py")
    print(f"  tests/test_{name}.py           (stub tests)")
    print(f"\nNext steps:")
    print(f"  1. Implement tools/{name}/{name}_tool.py")
    print(f"  2. Run: python -m tests.test_{name}")
    print(f"  3. Audit the code, Sir.")
    print(f"  4. Set enabled: true in tools/{name}/connector.json")
    print(f"  5. Full-chain test via the orchestrator.")
    print("=" * 60)


if __name__ == "__main__":
    main()
