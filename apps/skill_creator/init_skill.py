# apps/skill_creator/init_skill.py
# Scaffolds a new Aegon skill: connector.json + tool stub + __init__ + test stub.
# All generated skills start with enabled: false (Axiom 4 gate).
# Sir audits the code, fills TODOs, then sets enabled: true in connector.json.
#
# Usage (from project root, venv active):
#   python -m apps.skill_creator.init_skill

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
TOOLS_DIR = PROJECT_ROOT / "tools"
TESTS_DIR = PROJECT_ROOT / "tests"

DOMAINS = [
    "productivity", "communication", "finance", "health",
    "research", "creative", "smart-home", "government", "dev",
]
PERMISSION_LEVELS = ["read_only", "write_gated", "always_gated"]
RESPONSE_STYLES   = ["verbatim", "summarize", "raw", "confirm"]
MECHANISMS        = ["connector", "bundle", "proactive", "mode"]


# ── helpers ──────────────────────────────────────────────────────────────────

def _ask(prompt: str, default: str = "") -> str:
    hint = f" [{default}]" if default else ""
    value = input(f"{prompt}{hint}: ").strip()
    return value or default


def _choose(prompt: str, options: list[str]) -> str:
    print(f"\n{prompt}")
    for i, opt in enumerate(options, 1):
        print(f"  {i}. {opt}")
    while True:
        raw = input("Choice (number or name): ").strip().lower()
        if raw.isdigit() and 1 <= int(raw) <= len(options):
            return options[int(raw) - 1]
        if raw in options:
            return raw
        print(f"  Enter a number 1–{len(options)} or one of: {', '.join(options)}")


def _to_class_name(snake: str) -> str:
    """reminder → Reminder, smart_home → SmartHome"""
    return "".join(w.capitalize() for w in snake.split("_"))


def _validate_name(name: str) -> str:
    clean = "".join(c if c.isalnum() or c == "_" else "_" for c in name.lower())
    if not clean or not clean[0].isalpha():
        raise ValueError(f"Skill name must start with a letter. Got: {name!r}")
    return clean


# ── template generators ───────────────────────────────────────────────────────

def _connector_json(cfg: dict) -> str:
    doc = {
        "name":             cfg["name"],
        "version":          "1.0.0",
        "description":      cfg["description"],
        "domain":           cfg["domain"],
        "mechanism":        cfg["mechanism"],
        "permission_level": cfg["permission_level"],
        "enabled":          False,
        "response_style":   cfg["response_style"],
        "entry_point":      f"tools.{cfg['name']}.{cfg['name']}_tool.{cfg['class_name']}Connector",
        "input_schema":     {},
    }
    return json.dumps(doc, indent=2)


